// Text mode for the title and connection screens.
void setupText() {

  vdp_initTextMode(VDP_WHITE, VDP_DARK_BLUE, false);

  vdp_loadASCIIFont((uint8_t *)ASCII);

  vdp_enableVDPReadyInt();
}

void titleScreen() {

  vdp_clearScreen();

  printAt(12, 1, "NABU  HOCKEY");
  printAt(9, 2, "Drop-in 4 vs 4 online");

  printAt(2, 5, "Stick / arrows   skate");
  printAt(2, 6, "Fire / space     shoot or pass");
  printAt(2, 7, "R or B           pick a team");
  printAt(2, 8, "ESC              leave the rink");
}

void main() {

  uint8_t result;

  initNABULib();

  setupText();

  titleScreen();

  // Must come first: an older adapter would hang on any other mp_ call
  if (!mp_isSupported()) {

    printAt(2, 12, "Your Internet Adapter is too old.");
    printAt(2, 13, "Update it from nabu.ca to play.");

    while (true);
  }

  printAt(2, 12, "Connecting...");

  // mp_init(gameId)                                          NETWORK CALL
  //   Connects the adapter to nabu.ca for this game.
  result = mp_init(HOCKEY_GAME_ID);

  if (result != MP_OK) {

    showError("CONNECT", result);

    while (true);
  }

  // mp_getPlayerName(): the name saved in the adapter's settings, or ask for one
  mp_getPlayerName(_myName);

  if (_myName[0] == 0x00) {

    uint8_t len;

    printAt(2, 14, "Your name: ");

    len = readLine(_myName, MP_PLAYER_NAME_MAX);

    _myName[len] = 0x00;
  }

  while (true) {

    bool    closed;
    uint8_t key = 0;

    titleScreen();

    printAt(2, 12, "Hi ");
    vdp_print(_myName);

    printAt(2, 14, "Press SPACE or FIRE to play");

    // Wait for SPACE or the fire button (released first, so a held button from
    // the last game doesn't skip the title)
    while (_joyStatus[0] & Joy_Button)
      vdp_waitVDPReadyInt();

    while (key != KEY_SPACE && !(_joyStatus[0] & Joy_Button)) {

      if (isKeyPressed())
        key = getChar();
    }

    if (!findRink())
      continue;

    closed = playHockey();

    // mp_leave()
    //   Leaves the rink. Everyone else keeps playing; if I was the host one of
    //   them takes over (MP_FLAG_HOST_MIGRATION).
    mp_leave();

    initNABULIBAudio();

    setupText();

    if (closed) {

      titleScreen();

      printAt(2, 12, "The rink closed. Press a key.");

      getChar();
    }
  }
}
