// ---------------------------------------------------------------------------
// Rink physics (shared by the host and by everyone's prediction)
// ---------------------------------------------------------------------------

// Mirror a pixel position into the top-left quarter of the rink.
void mirrorPos(int16_t x, int16_t y, int16_t *mx, int16_t *my) {

  *mx = x <= 127 ? x : 255 - x;
  *my = y <= 103 ? y : 207 - y;
}

// True when a round object of radius r at pixel (x, y) pokes outside a rounded corner.
bool outsideCorner(int16_t x, int16_t y, uint8_t r) {

  int16_t mx;
  int16_t my;
  int16_t dx;
  int16_t dy;
  int16_t lim = CORNER_R - r;

  mirrorPos(x, y, &mx, &my);

  if (mx >= CORNER_X || my >= CORNER_Y)
    return false;

  dx = CORNER_X - mx;
  dy = CORNER_Y - my;

  return dx * dx + dy * dy > lim * lim;
}

// Bounces a speed off a rounded corner as if it were a 45 degree wall. Top-left and
// bottom-right corners swap and negate the speeds, the other two only swap them.
// Also takes away some speed (keep = numerator over 4).
void cornerBounce(int16_t x, int16_t y, int16_t *vx, int16_t *vy, uint8_t keep) {

  int16_t ox = *vx;
  int16_t oy = *vy;

  if ((x <= 127) == (y <= 103)) {

    *vx = -oy;
    *vy = -ox;
  } else {

    *vx = oy;
    *vy = ox;
  }

  *vx = (*vx * keep) >> 2;
  *vy = (*vy * keep) >> 2;
}

// Moves a skater one frame with its speed and keeps it on the ice.
void moveSkater(Skater *s) {

  int16_t ox = s->x;
  int16_t oy = s->y;

  s->x += s->vx;
  s->y += s->vy;

  if (s->x < ((RINK_LEFT + SKATER_R) << FP)) {

    s->x  = (RINK_LEFT + SKATER_R) << FP;
    s->vx = 0;
  } else if (s->x > ((RINK_RIGHT - SKATER_R) << FP)) {

    s->x  = (RINK_RIGHT - SKATER_R) << FP;
    s->vx = 0;
  }

  if (s->y < ((RINK_TOP + SKATER_R) << FP)) {

    s->y  = (RINK_TOP + SKATER_R) << FP;
    s->vy = 0;
  } else if (s->y > ((RINK_BOTTOM - SKATER_R) << FP)) {

    s->y  = (RINK_BOTTOM - SKATER_R) << FP;
    s->vy = 0;
  }

  if (outsideCorner(s->x >> FP, s->y >> FP, SKATER_R)) {

    s->x = ox;
    s->y = oy;

    cornerBounce(ox >> FP, oy >> FP, &s->vx, &s->vy, 2);
  }
}

// Where the puck sits on a carrier's stick, in 1/16 px.
void stickPos(Skater *s, int16_t *x, int16_t *y) {

  *x = clampInt(s->x + DX16[s->facing] * CARRY_DIST, (RINK_LEFT + PUCK_R) << FP, (RINK_RIGHT - PUCK_R) << FP);
  *y = clampInt(s->y + DY16[s->facing] * CARRY_DIST, (RINK_TOP + PUCK_R) << FP, (RINK_BOTTOM - PUCK_R) << FP);
}

// Slows a puck speed down a little (ice friction).
int16_t puckFriction(int16_t v) {

  if (v > 0) {

    v -= (v >> 6) + 1;

    if (v < 0)
      v = 0;
  } else if (v < 0) {

    v = -v;
    v -= (v >> 6) + 1;

    if (v < 0)
      v = 0;

    v = -v;
  }

  return v;
}

// Starts the goal celebration (host only, see hostScore()).
void hostScore(uint8_t team);

// Host: a goalie knocks the puck off a carrier's stick. dir is +1 for the left
// goalie (puck goes right) and -1 for the right goalie.
void hostPokeCheck(int16_t goalieX, int16_t goalieY, int8_t dir) {

  int16_t py = _puckY >> FP;

  _noPickup[_carrier] = SHOT_NO_PICKUP;
  _carrier            = NO_CARRIER;

  _puckX  = (goalieX + dir * 8) << FP;
  _puckVX = dir * 48;
  _puckVY = (py - goalieY) << 3;

  soundPickup();
}

// Host: checks a carried puck against the goalies and the nets. A goalie poke checks
// a carrier who skates into them. Skating the puck over the goal line from in front
// of the net is a goal.
void hostCarriedPuck(Skater *c) {

  int16_t px = _puckX >> FP;
  int16_t py = _puckY >> FP;
  int16_t cx = c->x >> FP;
  int16_t gy;

  gy = _goalieY[0] >> FP;

  if (absInt(px - GOALIE_X_L) <= 6 && absInt(py - gy) <= 9) {

    hostPokeCheck(GOALIE_X_L, gy, 1);

    return;
  }

  gy = _goalieY[1] >> FP;

  if (absInt(px - GOALIE_X_R) <= 6 && absInt(py - gy) <= 9) {

    hostPokeCheck(GOALIE_X_R, gy, -1);

    return;
  }

  if (py <= NET_TOP || py >= NET_BOTTOM)
    return;

  // Left net: blue scores
  if (px <= GOAL_LINE_L && px >= NET_BACK_L && cx > GOAL_LINE_L) {

    _carrier = NO_CARRIER;
    _puckX   = (GOAL_LINE_L - 5) << FP;
    _puckVX  = 0;
    _puckVY  = 0;

    hostScore(TEAM_BLUE);

    return;
  }

  // Right net: red scores
  if (px >= GOAL_LINE_R && px <= NET_BACK_R && cx < GOAL_LINE_R) {

    _carrier = NO_CARRIER;
    _puckX   = (GOAL_LINE_R + 5) << FP;
    _puckVX  = 0;
    _puckVY  = 0;

    hostScore(TEAM_RED);
  }
}

// Moves the free puck one frame: friction, boards, corners, nets and goalies.
// Only the host (authoritative = true) counts goals. Everyone else just stops the
// predicted puck in the net and waits for the host's packet.
void stepPuck(bool authoritative) {

  int16_t ox = _puckX;
  int16_t oy = _puckY;
  int16_t px;
  int16_t py;
  int16_t opx;
  int16_t gy;

  // Carried: the puck rides on the carrier's stick
  if (_carrier != NO_CARRIER) {

    Skater *c = &_skaters[_carrier];

    // Carrier's skater not heard from yet (just joined): leave the puck where it is.
    // The host frees the puck if the carrier really is gone.
    if (!c->active)
      return;

    stickPos(c, &_puckX, &_puckY);

    _puckVX = c->vx;
    _puckVY = c->vy;

    // Only the host decides poke checks and goals
    if (authoritative)
      hostCarriedPuck(c);

    return;
  }

  _puckX += _puckVX;
  _puckY += _puckVY;

  _puckVX = puckFriction(_puckVX);
  _puckVY = puckFriction(_puckVY);

  // Side boards
  if (_puckX < ((RINK_LEFT + PUCK_R) << FP)) {

    _puckX  = (RINK_LEFT + PUCK_R) << FP;
    _puckVX = (-_puckVX * 3) >> 2;
  } else if (_puckX > ((RINK_RIGHT - PUCK_R) << FP)) {

    _puckX  = (RINK_RIGHT - PUCK_R) << FP;
    _puckVX = (-_puckVX * 3) >> 2;
  }

  // Top and bottom boards
  if (_puckY < ((RINK_TOP + PUCK_R) << FP)) {

    _puckY  = (RINK_TOP + PUCK_R) << FP;
    _puckVY = (-_puckVY * 3) >> 2;
  } else if (_puckY > ((RINK_BOTTOM - PUCK_R) << FP)) {

    _puckY  = (RINK_BOTTOM - PUCK_R) << FP;
    _puckVY = (-_puckVY * 3) >> 2;
  }

  // Rounded corners
  if (outsideCorner(_puckX >> FP, _puckY >> FP, PUCK_R)) {

    _puckX = ox;
    _puckY = oy;

    cornerBounce(ox >> FP, oy >> FP, &_puckVX, &_puckVY, 3);
  }

  px  = _puckX >> FP;
  py  = _puckY >> FP;
  opx = ox >> FP;

  // Nets. Crossing a goal line between the posts is a goal, hitting the
  // sides or back of a net bounces off.
  if (py >= NET_TOP && py <= NET_BOTTOM) {

    // Left net (red defends it, so blue scores)
    if (px <= GOAL_LINE_L && px >= NET_BACK_L) {

      if (opx > GOAL_LINE_L && py > NET_TOP && py < NET_BOTTOM) {

        _puckX  = (GOAL_LINE_L - 5) << FP;
        _puckVX = 0;
        _puckVY = 0;

        if (authoritative)
          hostScore(TEAM_BLUE);

        return;
      }

      // Off the post, the back, or a side of the net
      if (opx > GOAL_LINE_L || opx < NET_BACK_L) {

        _puckX  = ox;
        _puckVX = -_puckVX;
      } else {

        _puckY  = oy;
        _puckVY = -_puckVY;
      }
    }

    // Right net (blue defends it, so red scores)
    if (px >= GOAL_LINE_R && px <= NET_BACK_R) {

      if (opx < GOAL_LINE_R && py > NET_TOP && py < NET_BOTTOM) {

        _puckX  = (GOAL_LINE_R + 5) << FP;
        _puckVX = 0;
        _puckVY = 0;

        if (authoritative)
          hostScore(TEAM_RED);

        return;
      }

      // Off the post, the back, or a side of the net
      if (opx < GOAL_LINE_R || opx > NET_BACK_R) {

        _puckX  = ox;
        _puckVX = -_puckVX;
      } else {

        _puckY  = oy;
        _puckVY = -_puckVY;
      }
    }
  }

  // Goalies kick back a puck coming at their net
  px = _puckX >> FP;
  py = _puckY >> FP;

  gy = _goalieY[0] >> FP;

  if (_puckVX < 0 && absInt(px - GOALIE_X_L) <= 6 && absInt(py - gy) <= 9) {

    _puckX  = (GOALIE_X_L + 7) << FP;
    _puckVX = (-_puckVX >> 1) + 8;
    _puckVY += (py - gy) << 2;
  }

  gy = _goalieY[1] >> FP;

  if (_puckVX > 0 && absInt(px - GOALIE_X_R) <= 6 && absInt(py - gy) <= 9) {

    _puckX  = (GOALIE_X_R - 7) << FP;
    _puckVX = (-_puckVX >> 1) - 8;
    _puckVY += (py - gy) << 2;
  }

  _puckVY = clampInt(_puckVY, -PUCK_MAX, PUCK_MAX);
}

// Moves both goalies toward their target height.
void moveGoalies(int16_t speed) {

  for (uint8_t g = 0; g < 2; g++)
    _goalieY[g] = approach(_goalieY[g], _goalieTgt[g], speed);
}

