// Fresh state for a rink I just joined or created. If someone else is the host their
// first puck packet replaces all of this.
void resetGame() {

  memset(_skaters, 0, sizeof(_skaters));
  memset(_rosterTeam, 0, sizeof(_rosterTeam));
  memset(_noPickup, 0, sizeof(_noPickup));
  memset(_lastMsg, 0, sizeof(_lastMsg));

  _myTeam        = TEAM_NONE;
  _carrier       = NO_CARRIER;
  _scoreRed      = 0;
  _scoreBlue     = 0;
  _clockSec      = GAME_SECONDS;
  _clockFrames   = 0;
  _stealCooldown = 0;
  _shotPredict   = 0;
  _keysHeld      = 0;
  _lastJoy       = _joyStatus[0];
  _shootPressed  = false;
  _sendFrames    = SEND_FRAMES;
  _startRetry    = 0;
  _frame         = 0;
  _rosterNext    = 0;
  _hudDirty      = true;
  _goalieY[0]    = CENTER_Y << FP;
  _goalieY[1]    = CENTER_Y << FP;
  _phaseTimer    = FACEOFF_FRAMES;

  enterPhase(PHASE_FACEOFF);

  // Nobody on a team yet: tell everyone (my player data might be left over)
  _playerData[0] = TEAM_NONE;

  mp_setPlayerData(_playerData);

  mp_status(&_status);

  _myId      = _status.myId;
  _isHost    = (_status.flags & MP_STATUS_IS_HOST) != 0;
  _rosterRev = _status.rosterRev;
}

// Plays on the rink until ESC or the rink closes. Returns true when the rink closed.
bool playHockey() {

  resetGame();

  setupRink();

  buildSprites();

  while (true) {

    // VRAM first, right after the vsync, while the VDP is not drawing
    vdp_waitVDPReadyInt();

    writeSprites();

    drawHud();

    if (!doNetwork())
      return true;

    if (!readKeys())
      return false;

    updateMe();

    updateRemotes();

    if (_isHost)
      hostUpdate();
    else
      clientUpdate();

    buildSprites();

    _frame++;
  }
}

