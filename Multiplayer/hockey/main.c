// Joins the busiest rink that still has room, or creates one. Returns false on error.
bool findRink() {

  uint8_t  result;
  uint8_t  count     = 0;
  uint16_t best      = 0;
  uint8_t  bestCount = 0;
  uint8_t  pos;

  printAt(2, 10, "Looking for a rink...");

  // mp_listSessions(filter, count)                          NETWORK CALL
  //   MP_LIST_ALL: rinks are always IN_GAME, which MP_LIST_JOINABLE would skip,
  //   so list them all and check each one for late join and room below.
  result = mp_listSessions(MP_LIST_ALL, &count);

  if (result != MP_OK) {

    showError("LIST", result);

    return false;
  }

  for (uint8_t i = 0; i < count; i++) {

    // mp_getSessionInfo(index, info): one rink from the list, no network wait
    mp_getSessionInfo(i, &_info);

    if (_info.sessionId == 0)
      continue;

    if (_info.flags & (MP_INFO_NEEDS_CODE | MP_INFO_LOCKED))
      continue;

    if (_info.playerCount >= _info.maxPlayers)
      continue;

    if (_info.state == MP_STATE_IN_GAME && !(_info.flags & MP_INFO_LATE_JOIN))
      continue;

    if (_info.state != MP_STATE_IN_GAME && _info.state != MP_STATE_LOBBY)
      continue;

    // Fill up the busiest rink first so players end up together
    if (best == 0 || _info.playerCount > bestCount) {

      best      = _info.sessionId;
      bestCount = _info.playerCount;
    }
  }

  if (best != 0) {

    printAt(2, 10, "Joining a rink...      ");

    // mp_join(sessionId, code, playerName, myId)              NETWORK CALL
    //   Late join works because the rink was created with MP_FLAG_LATE_JOIN.
    result = mp_join(best, NULL, (const char *)_myName, &_myId);

    if (result == MP_OK)
      return true;

    // Full or gone since the list was taken: make a new rink instead
  }

  printAt(2, 10, "Opening a new rink...  ");

  // Rink name like "DJ'S RINK"
  pos = 0;

  while (_myName[pos] != 0x00 && pos < 15) {

    _line[pos] = _myName[pos];

    pos++;
  }

  _line[pos] = 0x00;

  strcat((char *)_line, "'S RINK");

  // mp_create(maxPlayers, flags, code, playerName, sessionName, description, sessionId, myId)   NETWORK CALL
  //   MP_FLAG_LATE_JOIN       players can join while the game is playing
  //   MP_FLAG_HOST_MIGRATION  the rink keeps going when the host leaves
  result = mp_create(MAX_PLAYERS, MP_FLAG_LATE_JOIN | MP_FLAG_HOST_MIGRATION, NULL, (const char *)_myName, (const char *)_line, "Drop-in hockey, 4 vs 4. Join any time!", NULL, &_myId);

  if (result != MP_OK) {

    showError("CREATE", result);

    return false;
  }

  // mp_start()                                                NETWORK CALL
  //   The rink plays right away, with however many people are on it
  mp_start();

  return true;
}

