void printAt(uint8_t x, uint8_t y, const char *text) {

  vdp_setCursor2(x, y);

  vdp_print((uint8_t *)text);
}

int16_t absInt(int16_t v) {

  return v < 0 ? -v : v;
}

// Moves v toward target by at most step.
int16_t approach(int16_t v, int16_t target, int16_t step) {

  if (v < target) {

    v += step;

    if (v > target)
      v = target;
  } else if (v > target) {

    v -= step;

    if (v < target)
      v = target;
  }

  return v;
}

int16_t clampInt(int16_t v, int16_t lo, int16_t hi) {

  if (v < lo)
    return lo;

  if (v > hi)
    return hi;

  return v;
}

// Copies text into dst starting at pos (no terminator). Returns the new position.
uint8_t putText(uint8_t *dst, uint8_t pos, const char *text) {

  while (*text != 0x00 && pos < 32) {

    dst[pos] = (uint8_t)*text;

    pos++;
    text++;
  }

  return pos;
}

// Writes v (0 - 99) as two characters, right aligned.
uint8_t putNum2(uint8_t *dst, uint8_t pos, uint8_t v) {

  if (v > 99)
    v = 99;

  dst[pos] = v < 10 ? ' ' : '0' + v / 10;
  dst[pos + 1] = '0' + v % 10;

  return pos + 2;
}

// Fills dst with 32 spaces and a terminator.
void clearLine(uint8_t *dst) {

  memset(dst, ' ', 32);

  dst[32] = 0x00;
}

// Puts text in the middle of a 32 character line.
void centerText(uint8_t *dst, const char *text) {

  uint8_t len = strlen(text);

  clearLine(dst);

  putText(dst, (32 - len) / 2, text);
}

// Shows a failed call and waits for a key (text mode screens only).
void showError(const char *what, uint8_t result) {

  vdp_clearRows(20, 24);

  printAt(0, 20, what);
  vdp_print((uint8_t *)": ");

  // mp_resultName(): short upper-case name for the result code, never NULL
  vdp_print((uint8_t *)mp_resultName(result));

  // mp_getLastError(): the adapter's longer explanation, 64 bytes, NUL terminated
  mp_getLastError(_errText);

  _errText[39] = 0x00;

  printAt(0, 21, (const char *)_errText);

  printAt(0, 23, "Press a key");

  getChar();
}

