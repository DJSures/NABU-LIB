// ****************************************************************************************
// NABU MULTIPLAYER HOCKEY
//
// Drop-in, drop-out hockey for up to 8 players: 4 on RED, 4 on BLUE. The game never
// waits for anyone. Start it, and you land on a rink that is already playing (or a new
// one if every rink is full). Pick a team with R or B and skate on. Leave with ESC
// whenever you like and the game carries on for everyone else.
//
// How the network play works ("drop-in" pattern):
//
//   - One rink = one session, created with MP_FLAG_LATE_JOIN (join any time) and
//     MP_FLAG_HOST_MIGRATION (the rink survives its host leaving). The host starts the
//     session right away, so it is always IN_GAME.
//
//   - Every player owns their own skater. It moves on their NABU with no delay and its
//     position goes to everyone else 20 times a second on a "latest only" channel.
//
//   - The host owns the puck, the goalies, the score and the clock. It sends them all
//     in one packet 20 times a second, also "latest only". Because the whole game state
//     is in that packet, someone joining late, or a new host after a migration, is in
//     sync after one packet. Nothing needs a reliable "event" except a shot.
//
//   - Shooting: the skater carrying the puck sends a reliable MSG_SHOOT to the host and
//     shows the shot straight away (prediction). The host confirms it in its next puck
//     packet, or the puck snaps back if someone stole it first.
//
// Controls: joystick 1 or the arrow keys skate, FIRE or SPACE shoots/passes,
//           R or B picks a team, ESC leaves the rink.
//
// The rink and sprite pictures are in graphics.h, generated by makeGraphics.js.
//
// DJ Sures (c) 2026
// https://nabu.ca
// ****************************************************************************************

