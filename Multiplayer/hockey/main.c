// Everyone (host and players) runs this when the phase changes.
void enterPhase(uint8_t phase) {

  _phase    = phase;
  _hudDirty = true;

  switch (phase) {

    case PHASE_FACEOFF:

      _carrier      = NO_CARRIER;
      _shotPredict  = 0;
      _puckX        = CENTER_X << FP;
      _puckY        = CENTER_Y << FP;
      _puckVX       = 0;
      _puckVY       = 0;
      _goalieTgt[0] = CENTER_Y << FP;
      _goalieTgt[1] = CENTER_Y << FP;

      spawnMe();

      soundWhistle();

      break;

    case PHASE_PLAY:

      soundWhistle();

      break;

    case PHASE_GOAL_RED:
    case PHASE_GOAL_BLUE:

      _carrier = NO_CARRIER;

      soundGoal();

      break;

    case PHASE_END:

      _carrier = NO_CARRIER;

      soundBuzzer();

      break;
  }
}

// Host: shows the score on nabu.ca.
void hostStatusText() {

  uint8_t pos = 0;

  pos = putText(_line, pos, "RED ");
  pos = putNum2(_line, pos, _scoreRed);
  pos = putText(_line, pos, " - BLUE ");
  pos = putNum2(_line, pos, _scoreBlue);

  _line[pos] = 0x00;

  // mp_setStatusText(text)
  //   Host only. One line shown with the session on nabu.ca (max 63 characters).
  mp_setStatusText((const char *)_line);
}

// Host: a goal went in.
void hostScore(uint8_t team) {

  if (team == TEAM_RED) {

    if (_scoreRed < 99)
      _scoreRed++;

    _phaseTimer = GOAL_FRAMES;

    enterPhase(PHASE_GOAL_RED);
  } else {

    if (_scoreBlue < 99)
      _scoreBlue++;

    _phaseTimer = GOAL_FRAMES;

    enterPhase(PHASE_GOAL_BLUE);
  }

  hostStatusText();
}

// Host: who has the puck? Free pucks are picked up, carried pucks can be stolen.
void hostPossession() {

  int16_t px = _puckX >> FP;
  int16_t py = _puckY >> FP;

  if (_carrier != NO_CARRIER) {

    Skater *c = &_skaters[_carrier];

    // Carrier left the rink or went back to watching
    if (!c->active) {

      _carrier = NO_CARRIER;
      _puckVX  = 0;
      _puckVY  = 0;

      return;
    }

    if (_stealCooldown != 0)
      return;

    for (uint8_t i = 0; i < MP_MAX_PLAYERS; i++) {

      Skater *s = &_skaters[i];

      if (!s->active || s->team == c->team)
        continue;

      if (absInt((s->x >> FP) - px) < STEAL_DIST && absInt((s->y >> FP) - py) < STEAL_DIST) {

        _noPickup[_carrier] = SHOT_NO_PICKUP;
        _carrier            = i;
        _stealCooldown      = STEAL_COOLDOWN;

        soundPickup();

        return;
      }
    }

    return;
  }

  for (uint8_t i = 0; i < MP_MAX_PLAYERS; i++) {

    Skater *s = &_skaters[i];

    if (!s->active || _noPickup[i] != 0)
      continue;

    if (absInt((s->x >> FP) - px) < PICKUP_DIST && absInt((s->y >> FP) - py) < PICKUP_DIST) {

      _carrier       = i;
      _stealCooldown = STEAL_COOLDOWN / 2;

      soundPickup();

      return;
    }
  }
}

// Host: runs the puck, goalies, clock and phases. Everyone else copies the result.
void hostUpdate() {

  for (uint8_t i = 0; i < MP_MAX_PLAYERS; i++) {

    if (_noPickup[i] != 0)
      _noPickup[i]--;
  }

  if (_stealCooldown != 0)
    _stealCooldown--;

  switch (_phase) {

    case PHASE_PLAY:

      hostPossession();

      stepPuck(true);

      // A goal inside stepPuck() changes the phase, so only tick the clock while
      // the game is still on
      if (_phase != PHASE_PLAY)
        break;

      _clockFrames++;

      if (_clockFrames >= 60) {

        _clockFrames = 0;

        _clockSec--;

        _hudDirty = true;

        if (_clockSec == 0) {

          _phaseTimer = END_FRAMES;

          enterPhase(PHASE_END);
        }
      }

      break;

    case PHASE_FACEOFF:

      _phaseTimer--;

      if (_phaseTimer == 0)
        enterPhase(PHASE_PLAY);

      break;

    case PHASE_GOAL_RED:
    case PHASE_GOAL_BLUE:

      _phaseTimer--;

      if (_phaseTimer == 0) {

        _phaseTimer = FACEOFF_FRAMES;

        enterPhase(PHASE_FACEOFF);
      }

      break;

    case PHASE_END:

      _phaseTimer--;

      if (_phaseTimer == 0) {

        // New game: same players, fresh score and clock
        _scoreRed    = 0;
        _scoreBlue   = 0;
        _clockSec    = GAME_SECONDS;
        _clockFrames = 0;
        _phaseTimer  = FACEOFF_FRAMES;

        enterPhase(PHASE_FACEOFF);

        hostStatusText();
      }

      break;
  }

  // Goalies follow the puck up and down the crease
  if (_phase == PHASE_PLAY) {

    int16_t target = clampInt(_puckY >> FP, GOALIE_MIN_Y, GOALIE_MAX_Y) << FP;

    _goalieTgt[0] = target;
    _goalieTgt[1] = target;
  }

  moveGoalies(GOALIE_SPEED);
}

// Everyone but the host: keeps the puck moving between host packets.
void clientUpdate() {

  if (_shotPredict != 0)
    _shotPredict--;

  if (_phase == PHASE_PLAY)
    stepPuck(false);

  // Goalies glide to the height the host sent, a bit faster so they keep up
  moveGoalies(GOALIE_SPEED * 2);
}

// I just became the host (the old host left). The game carries on from the last
// state the old host sent, which I've been copying all along.
void hostTakeover() {

  memset(_noPickup, 0, sizeof(_noPickup));

  _stealCooldown = 0;
  _clockFrames   = 0;
  _shotPredict   = 0;

  // A phase timer at 0 would wrap around, start the next phase instead
  if (_phaseTimer == 0)
    _phaseTimer = 1;
}

