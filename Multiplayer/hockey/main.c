// Counts players on a team, me included, from the roster.
uint8_t teamCount(uint8_t team) {

  uint8_t count = 0;

  for (uint8_t i = 0; i < MP_MAX_PLAYERS; i++) {

    if (i == _myId)
      continue;

    if ((_status.playerMask & (1 << i)) && _rosterTeam[i] == team)
      count++;
  }

  if (_myTeam == team)
    count++;

  return count;
}

// Puts my skater on its face-off spot. My spot is decided by how many teammates have
// a lower player id, so everyone on a team gets a different spot without talking.
void spawnMe() {

  Skater  *me   = &_skaters[_myId];
  uint8_t  slot = 0;
  uint8_t  t;

  if (_myTeam == TEAM_NONE) {

    me->active = 0;

    return;
  }

  for (uint8_t i = 0; i < _myId; i++) {

    if ((_status.playerMask & (1 << i)) && _rosterTeam[i] == _myTeam)
      slot++;
  }

  if (slot >= TEAM_MAX)
    slot = TEAM_MAX - 1;

  t = _myTeam - 1;

  me->active = 1;
  me->team   = _myTeam;
  me->x      = SPAWN_X[t][slot] << FP;
  me->y      = SPAWN_Y[slot] << FP;
  me->vx     = 0;
  me->vy     = 0;
  me->facing = _myTeam == TEAM_RED ? 0 : 4;
  me->age    = 0;
}

// Joins a team if it has room. TEAM_NONE goes back to watching.
void pickTeam(uint8_t team) {

  if (team == _myTeam)
    return;

  if (team != TEAM_NONE && teamCount(team) >= TEAM_MAX)
    return;

  _myTeam = team;

  // Drop the puck if I was carrying it. As a player this only changes my screen
  // until the host's next packet; as the host it really frees the puck.
  if (_carrier == _myId)
    _carrier = NO_CARRIER;

  // mp_setPlayerData(data)
  //   data     8 bytes everyone can read from the roster with mp_getPlayer().
  //            Here byte 0 is my team, so the team counts are right for everyone,
  //            including players who are only watching.
  //   returns  MP_OK, or MP_ERR_NOT_IN_SESSION.
  _playerData[0] = _myTeam;

  mp_setPlayerData(_playerData);

  spawnMe();

  _hudDirty = true;
}

// If two players picked the last spot on a team at the same moment, the team has 5.
// The roster decides who moves: the one with the highest player id switches.
void fixTeamOverflow() {

  uint8_t lower = 0;
  uint8_t other;

  if (_myTeam == TEAM_NONE)
    return;

  for (uint8_t i = 0; i < _myId; i++) {

    if ((_status.playerMask & (1 << i)) && _rosterTeam[i] == _myTeam)
      lower++;
  }

  if (lower < TEAM_MAX)
    return;

  other = _myTeam == TEAM_RED ? TEAM_BLUE : TEAM_RED;

  if (teamCount(other) < TEAM_MAX)
    pickTeam(other);
  else
    pickTeam(TEAM_NONE);
}

// Turns the joystick and arrow keys into a direction (or DIR_NONE).
uint8_t readStick() {

  uint8_t joy = _joyStatus[0];
  int8_t  dx  = 0;
  int8_t  dy  = 0;

  if ((joy & Joy_Right) || (_keysHeld & HELD_RIGHT))
    dx++;

  if ((joy & Joy_Left) || (_keysHeld & HELD_LEFT))
    dx--;

  if ((joy & Joy_Down) || (_keysHeld & HELD_DOWN))
    dy++;

  if ((joy & Joy_Up) || (_keysHeld & HELD_UP))
    dy--;

  return DIR_FROM_INPUT[dy + 1][dx + 1];
}

// Reads the keyboard and the joystick button. Returns false when ESC was pressed.
bool readKeys() {

  uint8_t joy = _joyStatus[0];

  while (isKeyPressed()) {

    uint8_t key = getChar();

    if (key >= KEY_ARROW_RIGHT && key <= KEY_ARROW_DOWN) {

      // 0xE0 right, 0xE1 left, 0xE2 up, 0xE3 down
      _keysHeld |= 1 << (key - KEY_ARROW_RIGHT);
    } else if (key >= KEY_ARROW_RIGHT + KEY_RELEASED && key <= KEY_ARROW_DOWN + KEY_RELEASED) {

      _keysHeld &= ~(1 << (key - KEY_ARROW_RIGHT - KEY_RELEASED));
    } else if (key == KEY_SPACE) {

      _shootPressed = true;
    } else if (key == 'r' || key == 'R') {

      pickTeam(TEAM_RED);
    } else if (key == 'b' || key == 'B') {

      pickTeam(TEAM_BLUE);
    } else if (key == KEY_ESC) {

      return false;
    }
  }

  // Fire button: shoot on the press, not while held
  if ((joy & Joy_Button) && !(_lastJoy & Joy_Button))
    _shootPressed = true;

  // Watching: push the stick toward a team's end to join it
  if (_myTeam == TEAM_NONE) {

    if ((joy & Joy_Left) && !(_lastJoy & Joy_Left))
      pickTeam(TEAM_RED);
    else if ((joy & Joy_Right) && !(_lastJoy & Joy_Right))
      pickTeam(TEAM_BLUE);
  }

  _lastJoy = joy;

  return true;
}

// Host side of a shot: the puck leaves the shooter's stick. from must be carrying it,
// otherwise the shot lost a race with a steal and is ignored.
void applyShot(uint8_t from, uint8_t x, uint8_t y, int8_t vx, int8_t vy) {

  if (_carrier != from)
    return;

  _carrier       = NO_CARRIER;
  _puckX         = (int16_t)x << FP;
  _puckY         = (int16_t)y << FP;
  _puckVX        = vx;
  _puckVY        = vy;
  _noPickup[from] = SHOT_NO_PICKUP;

  soundShot();
}

// I'm carrying the puck and pressed fire.
void shoot() {

  Skater  *me = &_skaters[_myId];
  int16_t  sx;
  int16_t  sy;
  int16_t  vx = ((DX16[me->facing] * SHOT_SPEED) >> 4) + (me->vx >> 1);
  int16_t  vy = ((DY16[me->facing] * SHOT_SPEED) >> 4) + (me->vy >> 1);

  vx = clampInt(vx, -PUCK_MAX, PUCK_MAX);
  vy = clampInt(vy, -PUCK_MAX, PUCK_MAX);

  stickPos(me, &sx, &sy);

  if (_isHost) {

    applyShot(_myId, sx >> FP, sy >> FP, vx, vy);

    return;
  }

  _packet[0] = MSG_SHOOT;
  _packet[1] = sx >> FP;
  _packet[2] = sy >> FP;
  _packet[3] = (int8_t)vx;
  _packet[4] = (int8_t)vy;

  // mp_send(target, channel, len, data)
  //   target   MP_TARGET_HOST: only the host needs a shot, it owns the puck.
  //   channel  MP_CHANNEL_RELIABLE: a shot must never be lost or replaced.
  //   returns  MP_OK, or MP_ERR_RATE_LIMIT / MP_ERR_TOO_LARGE /
  //            MP_ERR_NOT_IN_SESSION, which all mean the packet was dropped.
  mp_send(MP_TARGET_HOST, MP_CHANNEL_RELIABLE, MSG_SHOOT_LEN, _packet);

  // Show the shot now. The host's next packets confirm it (or put the puck back on
  // my stick if it never arrived).
  _carrier     = NO_CARRIER;
  _puckX       = sx;
  _puckY       = sy;
  _puckVX      = vx;
  _puckVY      = vy;
  _shotPredict = SHOT_PREDICT;

  soundShot();
}

// Skates my player one frame from the stick.
void updateMe() {

  Skater  *me = &_skaters[_myId];
  uint8_t  dir;
  int16_t  top;
  int16_t  tx = 0;
  int16_t  ty = 0;

  if (_myTeam == TEAM_NONE) {

    me->active    = 0;
    _shootPressed = false;

    return;
  }

  me->active = 1;
  me->team   = _myTeam;

  // Everyone stands still on their spot during a face-off
  if (_phase == PHASE_FACEOFF) {

    me->vx        = 0;
    me->vy        = 0;
    _shootPressed = false;

    return;
  }

  dir = readStick();
  top = _carrier == _myId ? SKATE_MAX_PUCK : SKATE_MAX;

  if (dir != DIR_NONE) {

    me->facing = dir;

    tx = (DX16[dir] * top) >> 4;
    ty = (DY16[dir] * top) >> 4;

    me->vx = approach(me->vx, tx, SKATE_ACCEL);
    me->vy = approach(me->vy, ty, SKATE_ACCEL);
  } else {

    me->vx = approach(me->vx, 0, SKATE_GLIDE);
    me->vy = approach(me->vy, 0, SKATE_GLIDE);
  }

  moveSkater(me);

  if (_shootPressed && _carrier == _myId && _phase == PHASE_PLAY)
    shoot();

  _shootPressed = false;
}

// Slides everyone else along between their packets and hides anyone gone quiet.
void updateRemotes() {

  for (uint8_t i = 0; i < MP_MAX_PLAYERS; i++) {

    Skater *s = &_skaters[i];

    if (i == _myId || !s->active)
      continue;

    if (s->age >= SKATER_TIMEOUT) {

      s->active = 0;

      continue;
    }

    s->age++;

    moveSkater(s);
  }
}

