// Builds the sprite table for the next frame. The puck always comes first so it is
// never hidden. The rest rotate every frame: the TMS9918 only shows 4 sprites on one
// line, and rotating turns a missing 5th sprite into a flicker everyone can still see.
void buildSprites() {

  uint8_t  entX[10];
  uint8_t  entY[10];
  uint8_t  entPat[10];
  uint8_t  entCol[10];
  uint8_t  count = 0;
  uint8_t  start;
  uint8_t *p = _sat;

  // Goalies
  entX[0]   = GOALIE_X_L;
  entY[0]   = _goalieY[0] >> FP;
  entPat[0] = SPR_GOALIE_EAST;
  entCol[0] = VDP_MED_RED;

  entX[1]   = GOALIE_X_R;
  entY[1]   = _goalieY[1] >> FP;
  entPat[1] = SPR_GOALIE_WEST;
  entCol[1] = VDP_DARK_BLUE;

  count = 2;

  // Skaters. Mine is drawn in the team's light colour so I can find myself.
  for (uint8_t i = 0; i < MP_MAX_PLAYERS && count < 10; i++) {

    Skater *s = &_skaters[i];

    if (!s->active)
      continue;

    entX[count]   = s->x >> FP;
    entY[count]   = s->y >> FP;
    entPat[count] = SPR_SKATER + s->facing;

    if (s->team == TEAM_RED)
      entCol[count] = i == _myId ? VDP_LIGHT_RED : VDP_DARK_RED;
    else
      entCol[count] = i == _myId ? VDP_LIGHT_BLUE : VDP_DARK_BLUE;

    count++;
  }

  // Puck. Attribute bytes: y (top - 1), x (left), pattern name (x4 for 16x16), colour.
  *p++ = (_puckY >> FP) - 9;
  *p++ = (_puckX >> FP) - 8;
  *p++ = SPR_PUCK << 2;
  *p++ = VDP_BLACK;

  start = _rotate % count;

  _rotate++;

  for (uint8_t k = 0; k < count; k++) {

    uint8_t e = start + k;

    if (e >= count)
      e -= count;

    *p++ = entY[e] - 9;
    *p++ = entX[e] - 8;
    *p++ = entPat[e] << 2;
    *p++ = entCol[e];
  }

  // 0xD0 as a y position ends the sprite list
  *p++ = 0xD0;

  _satLen = p - _sat;
}

// Copies the sprite table into VRAM. Called right after the vsync.
void writeSprites() {

  uint8_t *p   = _sat;
  uint8_t *end = _sat + _satLen;

  vdp_setWriteAddress(_vdpSpriteAttributeTableAddr);

  while (p != end) {

    IO_VDPDATA = *p;

    p++;
  }
}

// Row 0: RED score, clock, BLUE score.
void drawScoreboard() {

  uint8_t pos;
  uint8_t min = _clockSec / 60;
  uint8_t sec = _clockSec % 60;

  clearLine(_hudLine);

  pos = putText(_hudLine, 1, "RED ");
  putNum2(_hudLine, pos, _scoreRed);

  _hudLine[14] = '0' + min;
  _hudLine[15] = ':';
  _hudLine[16] = '0' + sec / 10;
  _hudLine[17] = '0' + sec % 10;

  pos = putNum2(_hudLine, 25, _scoreBlue);
  putText(_hudLine, pos, " BLUE");

  printAt(0, 0, (const char *)_hudLine);
}

// Row 1: what is going on, or how to join a team.
void buildMessage() {

  uint8_t pos;

  if (_status.flags & MP_STATUS_RECONNECTING) {

    centerText(_msgLine, "RECONNECTING...");

    return;
  }

  switch (_phase) {

    case PHASE_GOAL_RED:

      centerText(_msgLine, "*** RED SCORES! ***");

      return;

    case PHASE_GOAL_BLUE:

      centerText(_msgLine, "*** BLUE SCORES! ***");

      return;

    case PHASE_END:

      if (_scoreRed > _scoreBlue)
        centerText(_msgLine, "RED WINS THE GAME!");
      else if (_scoreBlue > _scoreRed)
        centerText(_msgLine, "BLUE WINS THE GAME!");
      else
        centerText(_msgLine, "TIE GAME!");

      return;
  }

  clearLine(_msgLine);

  // Watching: show how to join and how full each team is
  if (_myTeam == TEAM_NONE) {

    pos = putText(_msgLine, 0, "R=RED ");
    _msgLine[pos] = '0' + teamCount(TEAM_RED);
    pos = putText(_msgLine, pos + 1, "/4  B=BLUE ");
    _msgLine[pos] = '0' + teamCount(TEAM_BLUE);
    putText(_msgLine, pos + 1, "/4  ESC=QUIT");

    return;
  }

  if (_phase == PHASE_FACEOFF) {

    centerText(_msgLine, "FACE OFF");

    return;
  }

  pos = putText(_msgLine, 0, _myTeam == TEAM_RED ? "TEAM RED " : "TEAM BLUE");
  pos = putText(_msgLine, pos + 3, "PLAYERS ");
  _msgLine[pos] = '0' + (_status.playerCount <= 9 ? _status.playerCount : 9);
  putText(_msgLine, pos + 4, "ESC=QUIT");
}

// Redraws the two text rows when something changed. Called right after the vsync.
void drawHud() {

  if (_hudDirty) {

    _hudDirty = false;

    drawScoreboard();
  }

  // The message only changes now and then: rebuild it 4 times a second
  if (_frame % 15 == 7) {

    buildMessage();

    if (memcmp(_msgLine, _lastMsg, 32) != 0) {

      memcpy(_lastMsg, _msgLine, 33);

      printAt(0, 1, (const char *)_msgLine);
    }
  }
}

// Switches to Graphic Mode 2 and draws the rink.
void setupRink() {

  const uint8_t blank[8] = { 0, 0, 0, 0, 0, 0, 0, 0 };

  vdp_clearVRAM();

  // Dark blue backdrop matches the boards. 16x16 sprites, not magnified.
  vdp_initG2Mode(VDP_DARK_BLUE, true, false, false, false);

  // Font in patterns 32 - 127, white on black for the scoreboard rows
  vdp_loadASCIIFont((uint8_t *)ASCII);

  for (uint8_t i = 32; i < 128; i++)
    vdp_colorizePattern(i, VDP_WHITE, VDP_BLACK);

  // Pattern 0 is plain ice
  vdp_loadPatternToId(0, (uint8_t *)blank);
  vdp_colorizePattern(0, VDP_WHITE, VDP_WHITE);

  // Rink tiles
  for (uint8_t t = 0; t < RINK_TILE_COUNT; t++) {

    vdp_loadPatternToId(RINK_TILE_ID[t], (uint8_t *)&RINK_TILE_PATTERN[t * 8]);
    vdp_loadColorToId(RINK_TILE_ID[t], (uint8_t *)&RINK_TILE_COLOR[t * 8]);
  }

  vdp_loadSpritePatternNameTable(SPRITE_COUNT, (uint8_t *)SPRITE_DATA);

  // Scoreboard rows, then the rink
  vdp_clearRows(0, RINK_FIRST_ROW);

  for (uint8_t y = 0; y < RINK_ROWS; y++) {

    for (uint8_t x = 0; x < 32; x++)
      vdp_putPattern(x, RINK_FIRST_ROW + y, RINK_MAP[y * 32 + x]);
  }

  vdp_enableVDPReadyInt();
}

