// Sends my skater to everyone else.
void sendSkater() {

  Skater  *me = &_skaters[_myId];
  uint8_t  result;

  _packet[0] = MSG_SKATER;
  _packet[1] = _myTeam;
  _packet[2] = me->x >> FP;
  _packet[3] = me->y >> FP;
  _packet[4] = (int8_t)me->vx;
  _packet[5] = (int8_t)me->vy;
  _packet[6] = me->facing;

  // mp_send(target, channel, len, data)
  //   target   MP_TARGET_OTHERS: everyone but me, I already know where I am.
  //   channel  CHANNEL_SKATER, a "latest only" channel: if the last position has not
  //            been read yet, this one replaces it. Old positions are useless.
  result = mp_send(MP_TARGET_OTHERS, CHANNEL_SKATER, MSG_SKATER_LEN, _packet);

  // Too fast for the server: send a bit less often from now on
  if (result == MP_ERR_RATE_LIMIT && _sendFrames < SEND_FRAMES_MAX)
    _sendFrames++;
}

// Host: sends the puck, goalies, score, clock and phase to everyone else.
void sendPuck() {

  uint8_t result;

  _packet[0]  = MSG_PUCK;
  _packet[1]  = _puckX >> FP;
  _packet[2]  = _puckY >> FP;
  _packet[3]  = (int8_t)_puckVX;
  _packet[4]  = (int8_t)_puckVY;
  _packet[5]  = _carrier;
  _packet[6]  = _goalieTgt[0] >> FP;
  _packet[7]  = _goalieTgt[1] >> FP;
  _packet[8]  = _scoreRed;
  _packet[9]  = _scoreBlue;
  _packet[10] = _clockSec;
  _packet[11] = _phase;
  _packet[12] = _phaseTimer;

  // Same "latest only" idea as the skaters, on its own channel
  result = mp_send(MP_TARGET_OTHERS, CHANNEL_PUCK, MSG_PUCK_LEN, _packet);

  if (result == MP_ERR_RATE_LIMIT && _sendFrames < SEND_FRAMES_MAX)
    _sendFrames++;
}

// A skater packet from another player.
void applySkater(uint8_t from) {

  Skater *s = &_skaters[from];

  // Back to watching
  if (_rx[1] != TEAM_RED && _rx[1] != TEAM_BLUE) {

    s->active = 0;

    return;
  }

  s->active = 1;
  s->team   = _rx[1];
  s->x      = (int16_t)_rx[2] << FP;
  s->y      = (int16_t)_rx[3] << FP;
  s->vx     = (int8_t)_rx[4];
  s->vy     = (int8_t)_rx[5];
  s->facing = _rx[6] & 0x07;
  s->age    = 0;
}

// The host's puck packet: copy the whole game state.
void applyPuck() {

  uint8_t carrier = _rx[5];

  // While my shot is on its way to the host, its packets still show me carrying the
  // puck. Ignore the puck part of those so the shot doesn't jump back.
  if (_shotPredict == 0 || carrier != _myId) {

    _shotPredict = 0;

    if (carrier == _myId && _carrier != _myId)
      soundPickup();

    _carrier = carrier < MP_MAX_PLAYERS ? carrier : NO_CARRIER;
    _puckX   = (int16_t)_rx[1] << FP;
    _puckY   = (int16_t)_rx[2] << FP;
    _puckVX  = (int8_t)_rx[3];
    _puckVY  = (int8_t)_rx[4];
  }

  _goalieTgt[0] = (int16_t)_rx[6] << FP;
  _goalieTgt[1] = (int16_t)_rx[7] << FP;

  if (_rx[8] != _scoreRed || _rx[9] != _scoreBlue || _rx[10] != _clockSec)
    _hudDirty = true;

  _scoreRed   = _rx[8];
  _scoreBlue  = _rx[9];
  _clockSec   = _rx[10];
  _phaseTimer = _rx[12];

  if (_rx[11] != _phase && _rx[11] <= PHASE_END)
    enterPhase(_rx[11]);
}

// Reads the next roster entry (one per frame, so a roster change never stalls a frame).
void readRoster() {

  while (_rosterNext < MP_MAX_PLAYERS) {

    uint8_t id = _rosterNext;

    _rosterNext++;

    if (!(_status.playerMask & (1 << id))) {

      _rosterTeam[id] = TEAM_NONE;

      continue;
    }

    if (id == _myId) {

      _rosterTeam[id] = _myTeam;

      continue;
    }

    // mp_getPlayer(playerId, player)
    //   player   an MpPlayerInfo to fill. playerData holds the 8 bytes the player set
    //            with mp_setPlayerData(): byte 0 is their team.
    //   returns  nothing. Answered from the adapter's memory.
    mp_getPlayer(id, &_player);

    _rosterTeam[id] = _player.playerData[0] <= TEAM_BLUE ? _player.playerData[0] : TEAM_NONE;

    _hudDirty = true;

    return;
  }

  // Whole roster read
  _rosterNext = 0xFF;

  fixTeamOverflow();
}

// Polls the session. Returns false when the rink is gone.
bool pollStatus() {

  bool wasHost = _isHost;

  // mp_status(status)
  //   Fills _status from the adapter's memory, cheap enough for every few frames.
  mp_status(&_status);

  if (_status.state == MP_STATE_NONE || _status.state == MP_STATE_ENDED || _status.state == MP_STATE_CLOSED)
    return false;

  _myId   = _status.myId;
  _isHost = (_status.flags & MP_STATUS_IS_HOST) != 0;

  if (_isHost && !wasHost)
    hostTakeover();

  // Someone joined, left or changed team: read the roster again
  if (_status.rosterRev != _rosterRev) {

    _rosterRev  = _status.rosterRev;
    _rosterNext = 0;
    _hudDirty   = true;
  }

  // Players who left the rink disappear right away
  for (uint8_t i = 0; i < MP_MAX_PLAYERS; i++) {

    if (i != _myId && !(_status.playerMask & (1 << i)))
      _skaters[i].active = 0;
  }

  // A rink that is not IN_GAME yet (just created, or after a host change): the host
  // starts it. Late join only applies to a started session.
  if (_startRetry != 0)
    _startRetry--;

  if (_status.state == MP_STATE_LOBBY && _isHost && _startRetry == 0) {

    // mp_start()                                             NETWORK CALL
    //   Host only. Moves the session to MP_STATE_IN_GAME.
    mp_start();

    _startRetry = 12;
  }

  return true;
}

// All the network work for one frame. Returns false when the rink is gone.
bool doNetwork() {

  uint8_t from;
  uint8_t sendPhase;

  if (_frame % STATUS_FRAMES == 0) {

    if (!pollStatus())
      return false;
  } else if (_rosterNext != 0xFF) {

    readRoster();
  }

  // Read what is waiting, a few packets per frame
  for (uint8_t n = 0; n < RECV_PER_FRAME; n++) {

    // mp_recv(buf, maxLen, from, channel)
    //   buf      where the packet's bytes are copied.
    //   maxLen   size of buf. Longer packets are truncated.
    //   from     receives the sender's player id.
    //   channel  receives the channel. NULL: the packet type says enough.
    //   returns  the number of bytes copied, or 0 when nothing is waiting.
    uint16_t len = mp_recv(_rx, sizeof(_rx), &from, NULL);

    if (len == 0)
      break;

    if (from >= MP_MAX_PLAYERS || from == _myId)
      continue;

    if (_rx[0] == MSG_SKATER && len >= MSG_SKATER_LEN)
      applySkater(from);
    else if (_rx[0] == MSG_PUCK && len >= MSG_PUCK_LEN && !_isHost && from == _status.hostId)
      applyPuck();
    else if (_rx[0] == MSG_SHOOT && len >= MSG_SHOOT_LEN && _isHost)
      applyShot(from, _rx[1], _rx[2], (int8_t)_rx[3], (int8_t)_rx[4]);
  }

  // My skater and (host) the puck, on alternate frames so they don't stack up
  sendPhase = _frame % _sendFrames;

  if (sendPhase == 0 && _myTeam != TEAM_NONE)
    sendSkater();

  if (sendPhase == 1 && _isHost)
    sendPuck();

  return true;
}

